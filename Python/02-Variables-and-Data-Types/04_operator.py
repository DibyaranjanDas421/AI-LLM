#Arithmatic operator
a=10
b=3
c=a+b #addtion
print(c)
d=a-b #subtraction
print(d)
e=a*b #multiplication
print(e)
f=a/b #division
print(f)
g=a%b #modulo
print(g)
h=a**b #exponential
print(h)
i=a//b #floor division
print(i)

#comparison operator
a=10
b=3
c=a>b #greater than
print(c)
d=a<b #less than
print(d)
e=a>=b #greater than or equal to
print(e)
f=a<=b #less than or equal to
print(f)
g=a==b #equal to
print(g)
h=a!=b #not equal to
print(h)


#Asssignment operator
a=b #equal to
print(a)

a+=b #addtion and assignment
print(a)

a-=b #subtraction and assignment
print(a)

a*=b #multiplication and assignment
print(a)

a/=b #division and assignment
print(a)

a%=b #modulo and assignment
print(a)

a**=b #exponential and assignment
print(a)

a//=b #floor division and assignment
print(a)


